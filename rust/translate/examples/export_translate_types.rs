use std::{env, fs, path::PathBuf};

use specta::TypeCollection;
use synth_translate::plugin::{dto::*, ErrorCode};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut types = TypeCollection::default();
    types
        .register::<ServiceSnapshot>()
        .register::<RequestDto>()
        .register::<OutcomeDto>()
        .register::<InventoryDto>()
        .register::<InstallPlanDto>();
    let declarations = specta_typescript::Typescript::default()
        .bigint(specta_typescript::BigIntExportBehavior::Number)
        .export(&types)?;
    let mut output = String::from("// Generated by export_translate_types. Do not edit.\n\n");
    output.push_str(
        declarations
            .replace("export type ", "// prettier-ignore\nexport type ")
            .trim_end(),
    );
    output.push_str("\n\n// prettier-ignore\nexport const commands = {");
    for command in translate_build::COMMANDS {
        output.push_str(&format!(" {command}: \"plugin:translate|{command}\","));
    }
    output.push_str(
        " } as const;\n\n// prettier-ignore\nexport const errorCodes: readonly ErrorCode[] = ",
    );
    output.push_str(&serde_json::to_string(ErrorCode::ALL)?);
    output.push_str(";\n");
    let destination = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../js/translate/types.ts");
    match env::args().nth(1).as_deref() {
        Some("--check") => {
            if fs::read_to_string(&destination)? != output {
                return Err("translation TypeScript contract is stale; regenerate it".into());
            }
        }
        Some("--write") => {
            fs::create_dir_all(destination.parent().unwrap())?;
            fs::write(destination, output)?;
        }
        None => print!("{output}"),
        _ => return Err("expected --check or --write".into()),
    }
    Ok(())
}
